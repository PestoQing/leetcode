# 某个大型软件项目的构建系统拥有 N 个文件，文件编号从 0 到 N - 1，在这些文件中，某些文件依赖于其他文件的内容，这意味着如果文件 A 依赖于文件 B，则必须在处理文件 A 之前处理文件 B （0 <= A, B <= N - 1）。请编写一个算法，用于确定文件处理的顺序。

# 输入描述
# 第一行输入两个正整数 N, M。表示 N 个文件之间拥有 M 条依赖关系。

# 后续 M 行，每行两个正整数 S 和 T，表示 T 文件依赖于 S 文件。

# 输出描述
# 输出共一行，如果能处理成功，则输出文件顺序，用空格隔开。 

# 如果不能成功处理（相互依赖），则输出 -1。

# 输入示例
# 5 4
# 0 1
# 0 2
# 1 3
# 2 4
# 输出示例
# 0 1 2 3 4

import sys
from collections import deque

# sys.stdin = open('input.txt', 'r')

data = sys.stdin.read().split()
n = int(data[0])
m = int(data[1])

graph = []
count = []
for i in range(n):
    graph.append([])
    count.append(0)

index = 2
for i in range(m):
    s = int(data[index])
    t = int(data[index + 1])
    # t 依赖 s，建立 s -> t；count[t] 记录尚未完成的前置依赖数。
    graph[s].append(t)
    count[t] += 1
    index += 2

queue = deque()
for i in range(n):
    if count[i] == 0:
        queue.append(i)

res = []
while queue:
    cur = queue.popleft()
    res.append(cur)
    for num in graph[cur]:
        count[num] -= 1
        if count[num] == 0:
            queue.append(num)

if len(res) == n:
    print(*res)
else:
    print(-1)


# 思路
# 使用入度法拓扑排序（Kahn 算法）。count[i] 是文件 i 尚未满足的依赖数。
# 先把所有入度为0的文件放入队列，这些文件可以直接处理。
# 每处理一个文件，就将它的后续文件入度减1；减为0的文件入队。
# 如果最后处理了全部 n 个文件，res 就是合法顺序；否则存在依赖环，输出-1。
#
# 常见问题
# 1. 为什么依赖关系写成 s -> t？
#    输入表示 t 依赖 s，因此 s 必须先处理；完成 s 后才能减少 t 的依赖。
# 2. 为什么只有入度为0才能入队？
#    入度为0表示所有前置文件已处理，可以安全处理当前文件。
# 3. 为什么处理不足 n 个文件就说明有环？
#    队列为空时，剩余每个节点仍有前置依赖；沿剩余依赖追溯必然遇到环。
#    有些节点可能只是被环阻塞，并不是所有剩余节点都在环上。
# 4. 为什么不需要额外 seen？
#    初始入度为0的节点只入队一次；其余节点的入度仅在减到0时入队一次。
#    每条边随起点处理一次，入度不会反复恢复，因此不会重复处理节点。
# 5. 时间和空间复杂度是多少？
#    建图 O(n+m)，每个节点入队出队一次，每条边遍历一次，总时间 O(n+m)。
#    邻接表与输入存储 O(n+m)，入度、队列、结果各 O(n)；总空间 O(n+m)。
#    deque.append 从右侧入队，popleft 从左侧出队，单次操作均为 O(1)。
# 6. 输出顺序是否唯一，需要每次选择最小编号吗？
#    不一定唯一；题目只要求合法顺序，没有要求字典序最小。
#    当前先按编号加入初始零入度文件，后续按邻接表顺序入队。
#    如要求字典序最小，应将普通队列改成最小堆。
# 7. 没有依赖、重复依赖和自环呢？
#    没有依赖时所有文件都会初始入队，按编号输出。
#    重复边在建图和减入度时都分别计数，结果仍然正确。
#    自环使对应文件的入度无法降为0，最终输出-1。
