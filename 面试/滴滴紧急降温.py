import sys

# 本地调试时取消下面这行注释
sys.stdin = open('input1.txt', 'r')

def main():
    # 1. 读取并解析输入数据
    data = sys.stdin.read().split() # 一次性读取所有输入，按空白字符拆分
    if not data:
        return
    n = int(data[0])       # 服务器数量 N
    a = int(data[1])       # 中心服务器降温量 A
    b = int(data[2])       # 其他服务器降温量 B
    h = [int(x) for x in data[3:3+n]]  # 每台服务器的初始过热指数列表

    # 2. 初始化二分查找
    d = a - b              # 中心服务器比普通服务器每次多减的量（A - B）
    L = 0                  # 二分查找下界：最少操作 0 次
    R = max(h)             # 二分查找上界：最多操作 max(h) 次（因为B>=1，每次至少减1，肯定够）

    # 3. 二分查找主循环
    while L < R:
        M = (L + R) // 2   # M 是当前假设的总操作次数
        
        # 4. 验证 M 次操作是否足够 (贪心策略)
        s = 0              # s 记录需要将某些服务器选为“中心”的总次数
        for x in h:
            # 如果经过 M 次全局降温 (每次减 B)，这台服务器还没降到 0 以下
            # 则它必须被选为“中心”至少若干次
            if x > M * b:
                # 额外需要减少 x - M*b
                # 每次被选为中心，可以额外多减 d
                # 向上取整计算需要选为中心的次数：(x - M*b + d - 1) // d
                s += (x - M * b + d - 1) // d
                
        # 5. 判断可行性并调整二分区间
        if s <= M:         # 如果所需中心次数 s 不超过总操作次数 M，说明 M 次操作可行
            R = M          # 尝试更少的操作次数
        else:              # 如果所需的中心次数超过了总操作次数，说明 M 次不够
            L = M + 1      # 必须增加操作次数

    # 6. 输出结果
    print(L)               # 当 L == R 时，即为最少需要的操作次数

if __name__ == "__main__":
    main()