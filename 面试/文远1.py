# 题目描述：
# 端侧最多缓存 m 个模型，初始缓存为空。
# 按顺序进行 n 次调用，模型编号为 nums[i]。
# 如果模型已经在缓存中，直接使用；否则需要加载，加载次数加 1。
# 缓存满时，可以卸载任意一个模型。
# 已知完整调用顺序，求最少加载次数。
#
# 输入：
# 第一行 m n
# 第二行 n 个模型编号
#
# 思路：
# 缓存满时，卸载下一次使用最晚的模型。
# 以后不再使用的模型优先卸载。
# 这是 Belady 最优缓存策略，需要提前知道全部调用序列。
# 直观理解：保留更早会被调用的模型，可以把下一次缓存缺失尽量推迟。
# 交换论证：若某最优方案先淘汰了更早要用的模型，可以改为淘汰最晚要用的
# 模型；在较早的那次调用前不会增加加载次数，之后也可调整回原方案。
# 因而每次采用该贪心选择，都能保留一个最优解。
#
# 实现分两步：倒序预处理下一次出现的位置，再用最大堆模拟缓存。
# Python 只有最小堆接口，这里存位置的相反数来实现最大堆。
# 时间复杂度 O(n log n)，空间复杂度 O(n)：堆保留旧记录，最多入堆 n 次。
# 本实现要求 m >= 1，且输入的调用序列长度为 n；m = 0 未单独处理。
#
# 测试 1 输入：
# 3 5
# 1 2 1 3 1
# 输出：
# 3
#
# 测试 2 输入：
# 2 6
# 1 2 3 1 2 3
# 输出：
# 4
#
# 测试 3 输入：
# 1 4
# 1 2 1 2
# 输出：
# 4

import sys
import heapq

# sys.stdin = open('input.txt', 'r')

# 一次性读取输入并按空白切分，模型编号仅用于判等，无需转成整数。
data = sys.stdin.read().split()
m = int(data[0])
n = int(data[1])
nums = data[2:]

# 倒序扫描时，last_seen[x] 是当前下标右侧距离最近的模型 x 的出现位置。
last_seen = {}
# 最终 next_pos[i] 表示第 i 次调用之后，同一模型下一次出现的位置。
next_pos = []

# 倒序记录每次调用后，该模型下一次出现的位置
for i in range(n - 1, -1, -1):
    x = nums[i]

    if x in last_seen:
        next_pos.append(last_seen[x])
    else:
        # 真实位置范围为 [0, n-1]，所以 n+i 比任何真实的未来位置都大。
        # 这使得不再使用的模型优先被淘汰；多个此类模型可任意选择。
        # 同时保留 i 的信息，出堆时减去 n 就能找回该模型。
        next_pos.append(n + i)

    # 当前出现成为更左侧位置所能看到的最近一次未来出现。
    last_seen[x] = i

# 刚才按 n-1 到 0 的顺序追加，翻转后才能直接按调用下标查询。
next_pos.reverse()

# seen 只记录实际留在缓存中的模型，集合查询的平均时间为 O(1)。
seen = set()
# heap 记录下一次使用位置的相反数，包含有效记录和尚未清理的旧记录。
heap = []
# res 为累计加载次数；缓存命中不增加次数。
res = 0

for i in range(n):
    x = nums[i]

    # 未命中必须加载；只有此时才可能需要腾出缓存空间。
    if x not in seen:
        res += 1

        if len(seen) == m:
            # 用负数入堆，取出下一次使用位置最大的模型
            pos = -heapq.heappop(heap)

            # 普通位置 pos 处的模型就是待淘汰模型；哨兵则先还原原下标。
            if pos >= n:
                pos -= n

            seen.remove(nums[pos])

        seen.add(x)

    # 无论是否命中，都记录本次调用之后的下一次使用位置。
    # 为什么不需要显式删除命中前的旧记录？
    # 模型再次被访问后，旧记录指向的出现位置已 <= i；而缓存内每个模型的
    # 最新记录都指向 > i 的未来位置或 >= n 的哨兵。
    # 淘汰发生在缓存未命中时，因此堆顶必定是某个在缓存内的模型的最新记录，
    # 旧记录不可能抢先出堆。被淘汰模型的最新记录则在淘汰时已弹出。
    heapq.heappush(heap, -next_pos[i])

print(res)